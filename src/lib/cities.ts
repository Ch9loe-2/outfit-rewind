/** 同分时优先展示的大城市，避免 "bj" 第一条是宝鸡 */
const HOT = new Set([
  '北京', '上海', '广州', '深圳', '杭州', '成都', '重庆', '武汉', '西安', '南京',
  '天津', '苏州', '长沙', '郑州', '青岛', '厦门', '昆明', '合肥', '福州', '济南',
  '大连', '宁波', '无锡', '沈阳', '哈尔滨', '乌鲁木齐', '拉萨', '海口', '三亚', '香港',
])

export function searchCities(query: string, limit = 10): CityEntry[] {
  const q = query.trim().toLowerCase().replace(/\s+/g, '')
  if (!q) return []

  const scored: Array<{ city: CityEntry; rank: number }> = []
  for (const city of CITIES) {
    const name = city.name.toLowerCase()
    const admin = (city.admin || '').toLowerCase()
    const py = city.pinyin || ''
    const ini = city.initials || ''
    let rank = -1
    if (name === q) rank = 0
    else if (name.startsWith(q)) rank = 1
    else if (py === q) rank = 2
    else if (py.startsWith(q)) rank = 3
    else if (ini === q) rank = 4
    else if (name.includes(q) || admin.startsWith(q)) rank = 5
    else if (py.includes(q)) rank = 6
    if (rank >= 0) scored.push({ city, rank })
  }

  scored.sort(
    (a, b) =>
      a.rank - b.rank ||
      Number(HOT.has(b.city.name)) - Number(HOT.has(a.city.name)) ||
      a.city.name.localeCompare(b.city.name, 'zh'),
  )
  return scored.slice(0, limit).map((item) => item.city)
}
